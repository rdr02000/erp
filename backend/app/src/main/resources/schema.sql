CREATE TABLE IF NOT EXISTS login_activities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    device_type VARCHAR(32) NOT NULL,
    browser VARCHAR(64) NOT NULL,
    operating_system VARCHAR(64) NOT NULL,
    user_agent VARCHAR(2048),
    latitude DOUBLE PRECISION,
    longitude DOUBLE PRECISION,
    accuracy_meters DOUBLE PRECISION,
    logged_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_login_activities_user_logged_at
    ON login_activities (user_id, logged_at DESC);


-- Master table for available products/services
CREATE TABLE IF NOT EXISTS products (
    product_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE,
    product_code VARCHAR(100) NOT NULL UNIQUE,
    description TEXT,
    price NUMERIC(12, 2),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Mapping table for user product subscriptions
CREATE TABLE IF NOT EXISTS user_product_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_users(id) ON DELETE CASCADE,
    product_id BIGINT NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE',
    subscribed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_user_product UNIQUE (user_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_user_product_subscriptions_user_id
    ON user_product_subscriptions (user_id);

CREATE INDEX IF NOT EXISTS idx_user_product_subscriptions_product_id
    ON user_product_subscriptions (product_id);
