DO $$
DECLARE
    has_legacy_company BOOLEAN;
    has_legacy_details BOOLEAN;
BEGIN
    SELECT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'user_profiles'
          AND column_name = 'company'
    ) INTO has_legacy_company;

    IF has_legacy_company THEN
        SELECT COUNT(DISTINCT column_name) = 6
        FROM information_schema.columns
        WHERE table_schema = current_schema()
          AND table_name = 'user_profiles'
          AND column_name = ANY (ARRAY[
              'company', 'company_industry', 'company_website',
              'company_email', 'company_phone', 'company_address'
          ]) INTO has_legacy_details;

        IF has_legacy_details THEN
            INSERT INTO companies (name, industry, website, email, phone, address)
            SELECT BTRIM(company),
                   MAX(NULLIF(BTRIM(company_industry), '')),
                   MAX(NULLIF(BTRIM(company_website), '')),
                   MAX(NULLIF(BTRIM(company_email), '')),
                   MAX(NULLIF(BTRIM(company_phone), '')),
                   MAX(NULLIF(BTRIM(company_address), ''))
            FROM user_profiles
            WHERE NULLIF(BTRIM(company), '') IS NOT NULL
            GROUP BY BTRIM(company)
            ON CONFLICT (name) DO UPDATE SET
                industry = COALESCE(companies.industry, EXCLUDED.industry),
                website = COALESCE(companies.website, EXCLUDED.website),
                email = COALESCE(companies.email, EXCLUDED.email),
                phone = COALESCE(companies.phone, EXCLUDED.phone),
                address = COALESCE(companies.address, EXCLUDED.address);
        ELSIF has_legacy_company THEN
            INSERT INTO companies (name)
            SELECT DISTINCT BTRIM(company)
            FROM user_profiles
            WHERE NULLIF(BTRIM(company), '') IS NOT NULL
            ON CONFLICT (name) DO NOTHING;
        END IF;

        UPDATE user_profiles AS profile
        SET company_id = company.company_id
        FROM companies AS company
        WHERE profile.company_id IS NULL
          AND NULLIF(BTRIM(profile.company), '') = company.name;
    END IF;
END $$;

